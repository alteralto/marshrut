function fullStaffingRoute(store, query, original) {
  const normalized = query.toLowerCase().trim().replace(/[.?!]+$/u, '').replace(/\s+/gu, ' ');
  if (original?.sha !== reviewedPdf || !staffingQuestion.test(normalized)) return null;
  const doc = store.docById.get(documentId);
  if (!doc || doc.meta?.supersededBy || doc.meta?.status === 'утратил силу') return null;
  const nodes = new Map(docView(doc, store).nodes.map(node => [node.id, node]));
  if (steps.some(step => step.clauses.some(clause => !nodes.has(clause)))) return null;
  const document = { id: doc.id, title: 'Регламент поиска и подбора персонала МФТИ', url: doc.url };
  return {
    document, documents: [document],
    summary: 'Маршрут обычного подбора по разделу 3. Заполните заявку, направьте её на согласование, разместите вакансию и проведите отбор. После решения и уведомления кадровой службы выберите путь приёма или отказа.',
    summary_cite: null,
    steps: steps.map(({ clauses, ...step }, index) => ({
      ...step, n: index + 1,
      cites: clauses.map(clause => {
        const node = nodes.get(clause);
        const page = clause === 'прил.1' ? 5 : node.page;
        return {
          doc: doc.id, docTitle: document.title, clause, anchor: node.anchor,
          quote: node.text, label: clause === 'прил.1' ? 'Приложение · форма заявки' : node.label,
          page, original: doc.url + (page ? '#page=' + page : ''),
        };
      }),
    })),
  };
}

