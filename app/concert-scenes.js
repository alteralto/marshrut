// Some clauses are nested in an OCR table row. Link to their own line and to
// the physically verified PDF page. The same page overrides cover appendices.
const verifiedPages = { '6.2': 5, '6.3': 5, '6.4': 5, '6.5': 5, 'прил.1': 6, 'прил.2': 8 };

function correctConcertOcr(entry, record) {
  if (entry.sha !== reviewedPdf) return record;
  const misread = 'Кто@иирега';
  const verified = 'kmo@mipt.ru';
  const at = record.text?.indexOf(misread) ?? -1;
  if (at < 0) return record;
  return {
    ...record,
    text: record.text.replace(misread, verified),
    pageStarts: record.pageStarts?.map(start => start > at ? start + verified.length - misread.length : start),
  };
}

function citeFor(doc, nodes, clause) {
  let node = nodes.find(n => n.id === clause);
  let anchor = node?.anchor;
  let quote = node?.text;
  if (!node && /^6\.[2-5]$/u.test(clause)) {
    for (const candidate of nodes) {
      const lines = candidate.text.split('\n');
      const index = lines.findIndex(line => line.trimStart().startsWith(clause + '. '));
      if (index < 1) continue;
      const end = lines.findIndex((line, i) => i > index && /^\s*(?:\d+\.\d+\.\s|7\.\s)/u.test(line));
      node = candidate;
      anchor = embeddedClauseAnchor(node.anchor, index);
      quote = lines.slice(index, end < 0 ? undefined : end).join('\n');
      break;
    }
  }
  if (!node) return null;
  const page = verifiedPages[clause] || node.page;
  return {
    doc: doc.id, docTitle: doc.title, clause, anchor, quote, page,
    label: clause.startsWith('прил.') ? 'Приложение № ' + clause.slice(5) : 'п. ' + clause,
    original: page ? doc.url + '#page=' + page : doc.url,
  };
}

function fullConcertRoute(store, question, original) {
  const key = question.toLowerCase().trim().replace(/[.?!]+$/u, '').replace(/\s+/gu, ' ');
  if (original?.sha !== reviewedPdf || !bookingQuestion.test(key)) return null;
  const doc = store.docById.get(documentId);
  if (!doc || doc.meta?.supersededBy || doc.meta?.status === 'утратил силу') return null;
  const { nodes } = docView(doc, store);
  const route = steps.map(({ clauses, ...step }, index) => ({
    ...step, n: index + 1, cites: clauses.map(clause => citeFor(doc, nodes, clause)),
  }));
  if (route.some(step => step.cites.includes(null))) return null;
  return {
    document: { id: doc.id, title: doc.title, url: doc.url },
    steps: route,
    summary: 'Согласуйте дату с культурно-массовым отделом. Для мероприятия вне перечня п. 6.1 подайте подписанную служебную записку не позднее чем за два месяца; для мероприятия из перечня основание — приказ. После включения в график подготовьте материалы и участников, проведите мероприятие и сдайте зал.',
    summary_cite: null,
  };
}

