function fullSupportRoute(store, query, original) {
  const normalized = query.toLowerCase().trim().replace(/[.?!]+$/u, '').replace(/\s+/gu, ' ');
  if (original?.sha !== reviewedPdf || !routeQuestion.test(normalized)) return null;
  const doc = store.docById.get(documentId);
  if (!doc || doc.meta?.supersededBy || doc.meta?.status === 'утратил силу') return null;
  const nodes = new Map(docView(doc, store).nodes.map(node => [node.id, node]));
  if (steps.some(item => item.clauses.some(clause => !nodes.has('прил.1/' + clause)))) return null;
  const document = { id: doc.id, title: doc.title, url: doc.url };
  return {
    document, documents: [document],
    summary: 'Подайте заявку через систему обращений или на почту техподдержки. При необходимости ответьте на уточнение. После выполнения работ проверьте результат. Если обратной связи нет 14 календарных дней, обращение закрывают.',
    summary_cite: null,
    steps: steps.map(({ clauses, ...item }, index) => ({
      ...item, n: index + 1,
      cites: clauses.map(number => {
        const clause = 'прил.1/' + number;
        const { anchor, text, label, page } = nodes.get(clause);
        return { doc: doc.id, docTitle: doc.title, clause, anchor, quote: text, label, page,
          ...(page ? { original: doc.url + '#page=' + page } : {}) };
      }),
    })),
  };
}

